// fits.ts — правила ответа про применимость, одни на все сайты.
//
// Прямой ручки «подходит ли деталь машине» нет ни у autodoc, ни у armtek:
// оба отвечают косвенно — каталогом категории, отфильтрованным по машине.
// Значит, и ошибаться они могут одинаково, и правила чтения этого каталога
// обязаны быть общими, иначе один сайт скажет «не подходит» там, где второй
// честно молчит.

import type { FitsResult } from "./contract.ts"

/**
 * Ниже этого числа каталог категории под машину — заглушка, а не подбор:
 * у autodoc «Метизы | Клипсы | Пистоны» под конкретную машину бывает два
 * десятка позиций, и «нет среди двадцати» не значит «не подходит».
 */
export const THIN_CATEGORY = 50

export type FitsScan = {
	/** Артикул нужного бренда нашёлся в подборе. */
	found: boolean
	/** Бренд вообще встречается в этом подборе — хоть каким-нибудь номером. */
	brandSeen: boolean
	/** Сколько позиций у сайта в этой категории под эту машину. */
	total: number
	/** Сколько из них мы успели просмотреть. */
	scanned: number
	/** Просмотрели всё, а не первые страницы. */
	complete: boolean
	/** Название категории и бренда — для причины, которую читает человек. */
	where: string
	brand: string
}

/**
 * Приговор по просмотренному каталогу. «Не подходит» — самый дорогой ответ:
 * по нему деталь не купят, поэтому он выдаётся только когда подбор сайта и
 * правда похож на каталог (позиций много), бренд в нём заведён, а номера в
 * нём нет. Во всех остальных случаях честнее «не знаю».
 */
export function fitsVerdict(s: FitsScan): FitsResult {
	if (s.found) return { fits: true, reason: `есть в «${s.where}» под эту машину` }
	if (!s.complete) {
		return { fits: null, reason: `просмотрено ${s.scanned} из ${s.total} позиций «${s.where}» под эту машину — дальше не смотрели` }
	}
	if (s.total < THIN_CATEGORY) {
		return { fits: null, reason: `в «${s.where}» под эту машину всего ${s.total} позиций — подбор сайта неполный` }
	}
	if (!s.brandSeen) {
		return { fits: null, reason: `бренда ${s.brand} в «${s.where}» под эту машину сайт не заводил` }
	}
	return { fits: false, reason: `нет в «${s.where}» под эту машину: просмотрено ${s.total} позиций, ${s.brand} среди них есть` }
}
